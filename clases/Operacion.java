package clases;

public class Operacion {

    public int metodoSuma(int numeroUno, int numeroDos) {
        int suma = numeroUno + numeroDos;
        return suma;
    }

    public int metodoResta(int numeroUno, int numeroDos) {
        int resta = numeroUno - numeroDos;
        return resta;
    }

    public int metodoMulti(int numeroUno, int numeroDos) {
        int multi = numeroUno * numeroDos;
        return multi;
    }

    public double metodoDiv(int numeroUno, int numeroDos) {
        double div = numeroUno / numeroDos;
        return div;
    }
}
